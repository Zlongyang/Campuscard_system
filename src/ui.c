#include "ui.h"



/*************************************************
* @brief 展示系统主菜单（角色选择）
**************************************************/
int ShowMainMenu(void)
{
    int input;
    system("cls");  // 清屏，Windows环境；Linux请替换为 system("clear")
    printf("==================== 模拟校园卡消费查询系统 ====================\n");
    printf("                    1. 学生登录\n");
    printf("                    2. 管理员登录\n");
    printf("                    0. 退出系统\n");
    printf("================================================================\n");
    printf("请输入您的选择：");
    // 主菜单选择校验
    while (scanf("%d", &input) != 1)
    {
        ClearInput();
        printf("输入非法，请输入数字！重新选择：");
    }
    ClearInput();
    return input;
}   


